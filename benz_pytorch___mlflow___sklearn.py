# Функция для очистки цены от всех видов пробелов и символов
def clean_price(price_str):
    """
    Очищает строку цены от символов валюты и пробелов
    Пример: "1 050 000 ₽" -> 1050000
    """
    if pd.isna(price_str):
        return 0

    # Убрать символ рубля
    price_str = str(price_str).replace('₽', '')
    # Убрать все виды пробелов (обычные, неразрывные и т.д.)
    price_str = re.sub(r'\s+', '', price_str).replace('\xa0', '')
    # Если после очистки осталась пустая строка
    if not price_str:
        return 0
    # Конвертируем в int
    return int(price_str)

