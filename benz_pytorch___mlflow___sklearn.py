# Функция для оценки модели в рублях (обратное преобразование из логарифма)
def evaluate_model_rub(y_true_log, y_pred_log):
    y_true_rub = np.expm1(y_true_log)
    y_pred_rub = np.expm1(y_pred_log)

    r2 = r2_score(y_true_rub, y_pred_rub)
    mae = mean_absolute_error(y_true_rub, y_pred_rub)
    rmse = np.sqrt(mean_squared_error(y_true_rub, y_pred_rub))
    mape = np.mean(np.abs((y_true_rub - y_pred_rub) / y_true_rub)) * 100

    return {
        'r2': r2,
        'mae': mae,
        'rmse': rmse,
        'mape': mape
    }

