class ImprovedPricePredictor(nn.Module):
    """
    Улучшенная нейросеть для предсказания цены автомобиля
    Особенности:
    - Residual connections (остаточные связи)
    - LayerNorm вместо BatchNorm (лучше для малых батчей)
    - Адаптивная скорость обучения
    - L2 регуляризация (weight decay)
    - Градиентный клиппинг
    """
    def __init__(self, input_dim, hidden_dims=[256, 128, 64, 32], dropout_rate=0.1):
        super(ImprovedPricePredictor, self).__init__()

        self.input_dim = input_dim

        # Входной слой
        self.input_layer = nn.Sequential(
            nn.Linear(input_dim, hidden_dims[0]),
            nn.LayerNorm(hidden_dims[0]),
            nn.ReLU(),
            nn.Dropout(dropout_rate)
        )

        # Скрытые слои с residual connections
        self.hidden_layers = nn.ModuleList()
        self.residual_connections = nn.ModuleList()

        for i in range(len(hidden_dims) - 1):
            in_dim = hidden_dims[i]
            out_dim = hidden_dims[i + 1]

            # Основной слой
            self.hidden_layers.append(nn.Sequential(
                nn.Linear(in_dim, out_dim),
                nn.LayerNorm(out_dim),
                nn.ReLU(),
                nn.Dropout(dropout_rate)
            ))

            # Residual connection (если размерности совпадают)
            if in_dim == out_dim:
                self.residual_connections.append(nn.Identity())
            else:
                self.residual_connections.append(nn.Linear(in_dim, out_dim))

        # Выходной слой
        self.output_layer = nn.Linear(hidden_dims[-1], 1)

        # Инициализация весов (Xavier/Glorot)
        self.apply(self._init_weights)

    def _init_weights(self, module):
        if isinstance(module, nn.Linear):
            nn.init.xavier_uniform_(module.weight)
            if module.bias is not None:
                nn.init.constant_(module.bias, 0)

    def forward(self, x):
        # Входной слой
        x = self.input_layer(x)

        # Скрытые слои с residual connections
        for i, layer in enumerate(self.hidden_layers):
            residual = self.residual_connections[i](x)
            x = layer(x)
            x = x + residual  # Residual connection

        # Выход
        x = self.output_layer(x)
        return x


class PriceDataset(torch.utils.data.Dataset):
    """Кастомный датасет с нормализацией"""
    def __init__(self, X, y):
        self.X = torch.FloatTensor(X)
        self.y = torch.FloatTensor(y.values if hasattr(y, 'values') else y).view(-1, 1)

    def __len__(self):
        return len(self.X)

    def __getitem__(self, idx):
        return self.X[idx], self.y[idx]


def train_pytorch_model(
    model,
    train_loader,
    test_loader,
    criterion,
    optimizer,
    scheduler,
    epochs=1000,
    patience=100,
    clip_grad_norm=1.0
):
    """
    Улучшенная функция обучения с:
    - Плато scheduler
    - Градиентный клиппинг
    - Сохранение лучшей модели
    - Мониторинг R²
    """
    train_losses = []
    test_losses = []
    train_r2_scores = []
    test_r2_scores = []

    best_test_loss = float('inf')
    best_test_r2 = -float('inf')
    patience_counter = 0
    best_model_state = None

    for epoch in range(epochs):
        # Training
        model.train()
        train_loss = 0
        all_train_preds = []
        all_train_targets = []

        for X_batch, y_batch in train_loader:
            optimizer.zero_grad()
            output = model(X_batch)
            loss = criterion(output, y_batch)
            loss.backward()

            # Градиентный клиппинг
            torch.nn.utils.clip_grad_norm_(model.parameters(), clip_grad_norm)

            optimizer.step()
            train_loss += loss.item()

            all_train_preds.append(output.detach().numpy())
            all_train_targets.append(y_batch.numpy())

        avg_train_loss = train_loss / len(train_loader)
        train_losses.append(avg_train_loss)

        # R² на train
        train_preds = np.concatenate(all_train_preds).flatten()
        train_targets = np.concatenate(all_train_targets).flatten()
        train_r2 = r2_score(train_targets, train_preds)
        train_r2_scores.append(train_r2)

        # Evaluation
        model.eval()
        test_loss = 0
        all_test_preds = []
        all_test_targets = []

        with torch.no_grad():
            for X_batch, y_batch in test_loader:
                output = model(X_batch)
                loss = criterion(output, y_batch)
                test_loss += loss.item()

                all_test_preds.append(output.numpy())
                all_test_targets.append(y_batch.numpy())

        avg_test_loss = test_loss / len(test_loader)
        test_losses.append(avg_test_loss)

        # R² на test
        test_preds = np.concatenate(all_test_preds).flatten()
        test_targets = np.concatenate(all_test_targets).flatten()
        test_r2 = r2_score(test_targets, test_preds)
        test_r2_scores.append(test_r2)

        # Scheduler step
        if scheduler is not None:
            scheduler.step(avg_test_loss)

        # Early stopping по R²
        if test_r2 > best_test_r2:
            best_test_r2 = test_r2
            best_test_loss = avg_test_loss
            best_model_state = model.state_dict().copy()
            patience_counter = 0
        else:
            patience_counter += 1
            if patience_counter >= patience:
                print(f"Early stopping at epoch {epoch} (best R² = {best_test_r2:.4f})")
                break

        # Печать прогресса
        if (epoch + 1) % 50 == 0:
            current_lr = optimizer.param_groups[0]['lr']
            print(f'Epoch [{epoch+1}/{epochs}] | '
                  f'Train Loss: {avg_train_loss:.4f} | '
                  f'Test Loss: {avg_test_loss:.4f} | '
                  f'Train R²: {train_r2:.4f} | '
                  f'Test R²: {test_r2:.4f} | '
                  f'LR: {current_lr:.2e}')

    # Load best model
    model.load_state_dict(best_model_state)

    return {
        'train_losses': train_losses,
        'test_losses': test_losses,
        'train_r2': train_r2_scores,
        'test_r2': test_r2_scores,
        'best_test_r2': best_test_r2,
        'best_test_loss': best_test_loss
    }

