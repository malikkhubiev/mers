# Извлечение информации из full_name
def parse_full_name(full_name):
    """
    Парсинг строки вида: "Mercedes-Benz C-класс 1.6 AT, 2019, 97 000 км"
    """
    if pd.isna(full_name):
        return pd.Series({'model': 'Unknown', 'year': 0, 'mileage': 0})

    # Разделение по запятой
    parts = full_name.split(',')

    # Если недостаточно частей, возвращение значения по умолчанию
    if len(parts) < 3:
        return pd.Series({'model': full_name[:50], 'year': 0, 'mileage': 0})

    # Первая часть содержит модель и комплектацию
    model_part = parts[0].strip()

    # Извлечение модели (Mercedes-Benz X-класс)
    # Поиск паттерна "Mercedes-Benz" + слово с дефисом или без
    model_match = re.search(r'(Mercedes-Benz[\w\-\s]+?)(?=\s\d|$)', model_part)
    if model_match:
        model = model_match.group(1).strip()
    else:
        # Если не нашли, берем первые слова до цифры
        words = []
        for word in model_part.split():
            if any(c.isdigit() for c in word):
                break
            words.append(word)
        model = ' '.join(words) if words else model_part[:30]

    # Извлечение года
    try:
        year = int(parts[1].strip())
    except:
        year = 0

    # Извлечение пробега
    try:
        mileage_str = parts[2].strip()
        # Удаление всех не-цифровых символов
        mileage_str = re.sub(r'[^\d]', '', mileage_str)
        mileage = int(mileage_str) if mileage_str else 0
    except:
        mileage = 0

    return pd.Series({
        'model': model,
        'year': year,
        'mileage': mileage
    })

